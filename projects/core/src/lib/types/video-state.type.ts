/**
 * Состояние медиа-элемента.
 *
 * - `idle` — элемент создан, но медиа ещё не загружено (нет метаданных);
 * - `playing` — идёт воспроизведение;
 * - `paused` — воспроизведение остановлено пользователем или кодом;
 * - `buffering` — идёт подгрузка данных, воспроизведение приостановлено;
 * - `seeking` — выполняется перемотка;
 * - `ended` — воспроизведение завершено;
 * - `error` — произошла ошибка (детали в `VideoError`).
 */
export type VideoState =
  'idle' | 'playing' | 'paused' | 'buffering' | 'seeking' | 'ended' | 'error';
